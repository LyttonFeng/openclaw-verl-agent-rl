#!/usr/bin/env bash
# Start a headless jiuwenclaw stack (agent_server + gateway, NO local vLLM).
# Points the OpenAIModelClient at an external vLLM via API_BASE env.
#
# Why headless: the default start_jiuwenclaw_stack.sh always launches its own
# vLLM (TP=2, ~56GB/card), which fights veRL's hybrid-engine vLLM for the same
# 2× A100 GPUs (that's what OOM-killed the v3 OpenClaw GRPO run on 2026-05-11).
#
# Path A: jiuwenclaw uses veRL's HTTP vLLM. openjiuwen-agent-core's
# OpenAIModelClient reads API_BASE/API_KEY/MODEL_NAME from env (or .env via
# --dotenv) and POSTs /v1/chat/completions there — zero code patch on the
# jiuwenclaw side.
#
# USAGE:
#   API_BASE=http://verl-host:12345/v1 \
#   MODEL_NAME=Qwen3-4B \
#   WS_PORT=611 \
#   bash start_jw_headless.sh
#
# Env knobs:
#   API_BASE              required — external vLLM URL ending in /v1
#   MODEL_NAME            required — served_model_name on the external vLLM
#   API_KEY               default "dummy"
#   WS_PORT               default 611  — gateway WebChannel WS port (clients connect here)
#   AGENT_SERVER_PORT     default 18092 (jiuwenclaw default)
#   JIUWENCLAW_DATA_DIR   default $HOME/.jiuwenclaw — set unique per-instance for isolation
#   LOG_DIR               default /tmp/jw_headless
#   JIUWENCLAW_REPO       default /root/jiuwen_work/jiuwenclaw
set -euo pipefail

: "${API_BASE:?Set API_BASE (external vLLM, e.g. http://127.0.0.1:8000/v1)}"
: "${MODEL_NAME:?Set MODEL_NAME (must match served_model_name on the external vLLM)}"
: "${API_KEY:=dummy}"
: "${MODEL_PROVIDER:=OpenAI}"

WS_PORT="${WS_PORT:-611}"                # WEB_PORT — clients connect here
AGENT_SERVER_PORT="${AGENT_SERVER_PORT:-18092}"
GATEWAY_PORT="${GATEWAY_PORT:-19001}"    # internal gateway service port (default 19001)
JIUWENCLAW_DATA_DIR="${JIUWENCLAW_DATA_DIR:-$HOME/.jiuwenclaw}"
LOG_DIR="${LOG_DIR:-/tmp/jw_headless}"
JIUWENCLAW_REPO="${JIUWENCLAW_REPO:-/root/jiuwen_work/jiuwenclaw}"
# Cap jiuwenclaw ReAct iterations (default 15 in jiuwenclaw; 40-turn long-tail
# trajectories in v50 wasted GPU). Maps to MAX_ITERATIONS env in
# app_web_handlers.py:304.
MAX_ITERATIONS="${MAX_ITERATIONS:-8}"
JW_VENV_PY="${JW_VENV_PY:-$JIUWENCLAW_REPO/.venv/bin/python}"

mkdir -p "$LOG_DIR" "$JIUWENCLAW_DATA_DIR"
TS=$(date +%Y%m%d_%H%M%S)
# Note: we intentionally do NOT seed identity files (SOUL/IDENTITY/HEARTBEAT/USER).
# jiuwenclaw runs without persona prompt and logs File not found warnings, but
# trajectories still complete. Bench MUST use the same script (no seed) for
# train/inference consistency — see bench_jw_async.sh.

if [ ! -x "$JW_VENV_PY" ]; then
  echo "[headless] FATAL: $JW_VENV_PY not executable. Set JW_VENV_PY." >&2
  exit 1
fi

# Optional reachability check on the external vLLM
echo "[headless] verifying external vLLM at $API_BASE ..."
if ! curl -sf --max-time 5 "${API_BASE%/}/models" > "$LOG_DIR/external_models_$TS.json"; then
  echo "[headless] WARN: GET ${API_BASE%/}/models failed — proceeding anyway" >&2
else
  echo "[headless] external models: $(python3 -c "import json; d=json.load(open('$LOG_DIR/external_models_$TS.json')); print([m['id'] for m in d['data']])" 2>/dev/null || true)"
fi

# Generate the .env that jiuwenclaw.app consumes via --dotenv. The jiuwenclaw
# bootstrap calls parse_dotenv_early() before initializing model clients;
# OpenAIModelClient picks up API_BASE/API_KEY (and config.yaml is bypassed
# when we don't supply one — env-var fallback kicks in).
ENV_FILE="$LOG_DIR/jw_headless_$TS.env"
cat > "$ENV_FILE" <<EOF
# Path-A headless jiuwenclaw env, generated by start_jw_headless.sh @ $TS
API_BASE=${API_BASE}
API_KEY=${API_KEY}
MODEL_NAME=${MODEL_NAME}
MODEL_PROVIDER=${MODEL_PROVIDER}
# Bind ports (gateway WS = WEB_PORT; clients connect ws://host:WEB_PORT/ws)
AGENT_SERVER_HOST=127.0.0.1
AGENT_SERVER_PORT=${AGENT_SERVER_PORT}
WEB_HOST=0.0.0.0
WEB_PORT=${WS_PORT}
WEB_PATH=/ws
GATEWAY_PORT=${GATEWAY_PORT}
# Per-instance workspace dir (avoid clashing with concurrent stacks)
JIUWENCLAW_DATA_DIR=${JIUWENCLAW_DATA_DIR}
# Cap ReAct iterations per chat.send (default 15)
MAX_ITERATIONS=${MAX_ITERATIONS}
EOF
echo "[headless] dotenv: $ENV_FILE"

cd "$JIUWENCLAW_REPO"

# Belt-and-suspenders: also export to process env in case jiuwenclaw.app's
# --dotenv only reads a hardcoded location rather than our --dotenv path.
# os.getenv() in get_default_models() reads from process env directly.
export API_BASE API_KEY MODEL_NAME MODEL_PROVIDER
export AGENT_SERVER_HOST=127.0.0.1
export AGENT_SERVER_PORT WEB_PORT="$WS_PORT" WEB_HOST=0.0.0.0 WEB_PATH=/ws
export GATEWAY_PORT JIUWENCLAW_DATA_DIR MAX_ITERATIONS

# Also drop a .env at the standard location so jiuwenclaw's own bootstrap
# (which auto-creates $DATA_DIR/config/) picks it up.
mkdir -p "$JIUWENCLAW_DATA_DIR/config"
cp -f "$ENV_FILE" "$JIUWENCLAW_DATA_DIR/config/.env"

LOG="$LOG_DIR/jw_app_$TS.log"
echo "[headless] launching jiuwenclaw.app -> $LOG"
nohup "$JW_VENV_PY" -m jiuwenclaw.app --dotenv "$ENV_FILE" \
  > "$LOG" 2>&1 &
APP_PID=$!
echo "$APP_PID" > "$LOG_DIR/jw_app.pid"
echo "[headless] PID=$APP_PID"

# Wait for the WebChannel WS to come up
echo "[headless] waiting for ws://127.0.0.1:$WS_PORT/ws (up to 60s)..."
for i in $(seq 1 60); do
  if ! kill -0 "$APP_PID" 2>/dev/null; then
    echo "[headless] FATAL: jiuwenclaw.app exited before WS came up. Last log:"
    tail -40 "$LOG" >&2
    exit 2
  fi
  if (echo > /dev/tcp/127.0.0.1/"$WS_PORT") 2>/dev/null; then
    echo "[headless] ws ready (${i}s)"
    break
  fi
  sleep 1
done

META="$LOG_DIR/stack_latest.env"
{
  echo "WS_URL=ws://127.0.0.1:$WS_PORT/ws"
  echo "MODEL_NAME=$MODEL_NAME"
  echo "API_BASE=$API_BASE"
  echo "AGENT_SERVER_PORT=$AGENT_SERVER_PORT"
  echo "MODE=path-a-headless"
  echo "PID=$APP_PID"
  echo "LOG=$LOG"
  echo "DOTENV=$ENV_FILE"
} > "$META"
echo "[headless] meta: $META"
